// Writes THIRD-PARTY-NOTICES.md: the full licence text of every npm package bundled into Pigmento,
// which ships with the app and shows in Help > About. The build checks that every package it bundles
// is listed there at its installed version (electron.vite.config.ts), and a unit test checks the
// texts are current, so run `npm run notices` after adding or updating a package the app uses.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

/** Every npm package bundled into the app (main, preload and renderer). */
export const PACKAGES = [
  'react',
  'react-dom',
  'scheduler',
  'zustand',
  'zod',
  'lucide-react',
  '@fontsource-variable/inter',
  'gifenc',
  'fflate',
];

export const NOTICES_FILE = path.join(root, 'THIRD-PARTY-NOTICES.md');

function licenceFile(dir) {
  const name = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));
  if (!name) throw new Error(`No licence file in ${dir}`);
  return path.join(dir, name);
}

/** The notices for the packages as installed in node_modules. */
export function renderNotices() {
  const parts = [
    '# Third-party licence texts',
    '',
    'The full licence texts of the open-source packages bundled into Pigmento (summarised in LICENSES.md). The licences of Electron, Chromium and Node.js ship with the app as LICENSE.electron.txt and LICENSES.chromium.html. This file is generated by `npm run notices`.',
    '',
  ];
  for (const name of PACKAGES) {
    const dir = path.join(root, 'node_modules', ...name.split('/'));
    const pkg = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8'));
    const text = readFileSync(licenceFile(dir), 'utf8').replace(/\r\n?/g, '\n').trim();
    parts.push(
      `## ${name} ${pkg.version}`,
      '',
      `Licence: ${pkg.license}`,
      '',
      '```',
      text,
      '```',
      '',
    );
  }
  return parts.join('\n');
}

/** The packages a notices file lists, with their versions. */
export function listedPackages(notices) {
  const listed = new Map();
  for (const m of notices.matchAll(/^## (\S+) (\d\S*)$/gm)) listed.set(m[1], m[2]);
  return listed;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(NOTICES_FILE, renderNotices());
  console.warn(`Wrote ${path.relative(root, NOTICES_FILE)} (${PACKAGES.length} packages)`);
}
